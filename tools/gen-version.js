// Writes cep/js/version.js from the extension manifest, so the panel can show which version it is.
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const m = fs.readFileSync(path.join(root, "cep/CSXS/manifest.xml"), "utf8").match(/ExtensionBundleVersion="([^"]+)"/);
if (!m) { console.error("no ExtensionBundleVersion in the manifest"); process.exit(1); }
fs.writeFileSync(path.join(root, "cep/js/version.js"), '// Generated by tools/gen-version.js from CSXS/manifest.xml\nwindow.CW_VERSION = "' + m[1] + '";\n');
console.log("version " + m[1]);
