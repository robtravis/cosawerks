// Writes cep/js/ease-presets.js from src/modules/ease_presets.jsx so the panel and the
// ExtendScript host share ONE list of curves. Run by install-cep.sh.
var fs = require("fs"), path = require("path");
var root = path.join(__dirname, "..");
var CW = { ease: {} };
new Function("CW", fs.readFileSync(path.join(root, "src/modules/ease_presets.jsx"), "utf8"))(CW);
var out = "// GENERATED by tools/gen-ease-presets.js. Do not edit.\nwindow.EASE_PRESETS = " + JSON.stringify({ RT: CW.ease.RT, MW: CW.ease.MW }) + ";\n";
fs.writeFileSync(path.join(root, "cep/js/ease-presets.js"), out);
console.log("ease presets:", CW.ease.RT.length, "RT +", CW.ease.MW.length, "MW");
