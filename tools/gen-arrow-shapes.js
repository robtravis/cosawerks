// Writes cep/js/arrow-shapes.js from src/modules/arrow_shapes.jsx, so the panel's head icons are drawn from the
// very same outlines the host builds. Run by install-cep.sh.
var fs = require("fs"), path = require("path");
var root = path.join(__dirname, "..");
var CW = {};
new Function("CW", fs.readFileSync(path.join(root, "src/modules/arrow_shapes.jsx"), "utf8"))(CW);

function f(n) { return (Math.round(n * 100) / 100).toString(); }
function pathData(g) {
  if (g.kind === "polygon") {
    var pts = [], k;
    for (k = 0; k < g.points; k++) { var a = (k * 360 / g.points) * Math.PI / 180; pts.push([g.center[0] + g.radius * Math.cos(a), g.center[1] + g.radius * Math.sin(a)]); }
    return "M" + pts.map(function (p) { return f(p[0]) + " " + f(p[1]); }).join("L") + "Z";
  }
  var v = g.vertices, i = g.inTangents, o = g.outTangents, d = "M" + f(v[0][0]) + " " + f(v[0][1]), n = v.length, k2;
  var hasCurves = o.some(function (t) { return t[0] || t[1]; }) || i.some(function (t) { return t[0] || t[1]; });
  for (k2 = 1; k2 <= (g.closed ? n : n - 1); k2++) {
    var a = v[k2 - 1], b = v[k2 % n];
    if (hasCurves) d += "C" + f(a[0] + o[k2 - 1][0]) + " " + f(a[1] + o[k2 - 1][1]) + " " + f(b[0] + i[k2 % n][0]) + " " + f(b[1] + i[k2 % n][1]) + " " + f(b[0]) + " " + f(b[1]);
    else d += "L" + f(b[0]) + " " + f(b[1]);
  }
  return d + (g.closed ? "Z" : "");
}
var out = { types: CW.arrowShapes.TYPES, shapes: {} };
CW.arrowShapes.TYPES.forEach(function (t) {
  var g = CW.arrowShapes.get(t[0]), xs = g.kind === "polygon" ? [g.center[0] - g.radius, g.center[0] + g.radius] : g.vertices.map(function (v) { return v[0]; });
  out.shapes[t[0]] = { d: pathData(g), stroked: !!g.stroked, cx: Math.round((Math.min.apply(null, xs) + Math.max.apply(null, xs)) / 2) };   // centre, so every icon is framed on its own shape
});
fs.writeFileSync(path.join(root, "cep/js/arrow-shapes.js"), "// GENERATED by tools/gen-arrow-shapes.js. Do not edit.\nwindow.ARROW_SHAPES = " + JSON.stringify(out) + ";\n");
console.log("arrow shapes:", CW.arrowShapes.TYPES.length);
