#!/usr/bin/env python3
"""Draw the panel icons as crisp PNGs (rects on a 24px grid) and embed them in
src/ui/05_icons.jsx as binary-string literals, so dist/Cosawerks.jsx stays one file.
Also writes assets/icons/*.png for reference. Run: python3 tools/make_icons.py"""
import struct, zlib, os

SIZE = 24
ICONS = {  # ["f", x, y, w, h] filled rect; ["o", x, y, w, h] 2px outline
    "alignLeft":   [["f",3,3,2,18],["f",7,6,13,5],["f",7,13,8,5]],
    "alignHC":     [["f",11,3,2,18],["f",4,6,16,5],["f",6,13,12,5]],
    "alignRight":  [["f",19,3,2,18],["f",4,6,13,5],["f",9,13,8,5]],
    "alignTop":    [["f",3,3,18,2],["f",6,7,5,13],["f",13,7,5,8]],
    "alignVC":     [["f",3,11,18,2],["f",4,6,5,12],["f",13,4,5,16]],
    "alignBottom": [["f",3,19,18,2],["f",6,4,5,13],["f",13,9,5,8]],
    "alignCenter": [["f",11,3,2,18],["f",3,11,18,2],["o",7,7,10,10]],
}

def raster(spec, rgba):
    px = [[(0, 0, 0, 0)] * SIZE for _ in range(SIZE)]
    def fill(x, y, w, h):
        for j in range(y, y + h):
            for i in range(x, x + w):
                if 0 <= i < SIZE and 0 <= j < SIZE: px[j][i] = rgba
    for kind, x, y, w, h in spec:
        if kind == "f": fill(x, y, w, h)
        else:
            t = 2
            fill(x, y, w, t); fill(x, y + h - t, w, t); fill(x, y, t, h); fill(x + w - t, y, t, h)
    return px

def png(px):
    raw = b"".join(b"\x00" + b"".join(bytes(p) for p in row) for row in px)
    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xffffffff)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))

def literal(data):
    return '"' + "".join("\\x%02x" % b for b in data) + '"'

os.makedirs("assets/icons", exist_ok=True)
lines = ["// GENERATED by tools/make_icons.py. Do not edit.",
         "// Each icon: [normal, pressed] PNG binary strings for ScriptUI iconbutton.",
         "CW.ICONS = {"]
names = sorted(ICONS)
for n, name in enumerate(names):
    normal = png(raster(ICONS[name], (205, 205, 205, 255)))
    pressed = png(raster(ICONS[name], (255, 255, 255, 255)))
    open("assets/icons/%s.png" % name, "wb").write(normal)
    lines.append('    %s: [%s, %s]%s' % (name, literal(normal), literal(pressed), "," if n < len(names) - 1 else ""))
lines.append("};")
open("src/ui/05_icons.jsx", "w").write("\n".join(lines) + "\n")
print("wrote", len(names), "icons")
