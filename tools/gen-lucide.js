// Builds cep/js/lucide-icons.js (shapes + search tags) from an unpacked lucide-static package.
//   npm pack lucide-static && tar -xzf lucide-static-*.tgz
//   node tools/gen-lucide.js /path/to/package
// The package itself is not kept in this repo; only the shapes, the tags and its license are.
var fs = require("fs"), path = require("path");
var src = process.argv[2];
if (!src) { console.error("usage: node tools/gen-lucide.js <unpacked lucide-static package folder>"); process.exit(1); }
var nodes = JSON.parse(fs.readFileSync(path.join(src, "icon-nodes.json"), "utf8"));
var tags = JSON.parse(fs.readFileSync(path.join(src, "tags.json"), "utf8"));
var version = JSON.parse(fs.readFileSync(path.join(src, "package.json"), "utf8")).version;

function attr(o) {
  return Object.keys(o).filter(function (k) { return k !== "key"; }).map(function (k) { return k + '="' + String(o[k]).replace(/"/g, "&quot;") + '"'; }).join(" ");
}
var out = {}, n = 0;
Object.keys(nodes).sort().forEach(function (name) {
  var markup = nodes[name].map(function (e) { return "<" + e[0] + " " + attr(e[1]) + "/>"; }).join("");
  out[name] = [markup, (tags[name] || []).join(" ")];
  n++;
});
var js = "// GENERATED by tools/gen-lucide.js from lucide-static " + version + " (ISC license, see licenses/LUCIDE-LICENSE.txt). Do not edit.\n" +
         "window.LUCIDE_VERSION = " + JSON.stringify(version) + ";\nwindow.LUCIDE = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(__dirname, "../cep/js/lucide-icons.js"), js);
fs.copyFileSync(path.join(src, "LICENSE"), path.join(__dirname, "../cep/licenses/LUCIDE-LICENSE.txt"));
console.log("lucide-static", version + ":", n, "icons,", Math.round(js.length / 1024) + " KB");
